"""Marks Grey's speech as AI-generated, the two ways the website and Grey Studio do (dashboard/server.py ai_wav):
- a label inside the WAV file (RIFF INFO, with the IPTC term for AI-made media, "trainedAlgorithmicMedia"),
- an inaudible AudioSeal watermark in the sound itself (survives MP3, resampling and moderate noise; the label doesn't).
The EU AI Act (Regulation (EU) 2024/1689, article 50(2)) asks this of AI systems that make synthetic audio.

    from dacts.marking import write_ai_wav, detect
    write_ai_wav("out.wav", wav, 44100)      # labelled + watermarked
    detect("out.wav")                         # -> watermark score 0..1 (> 0.5: Grey's mark)
"""
import io
import threading
import time
from pathlib import Path

import numpy as np

COMMENT = ("This audio was generated by AI (Grey, https://thisvoiceisai.com). It is not a recording of a person speaking. "
           "digitalSourceType=http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia")
_WM = {"lock": threading.Lock(), "gen": None, "det": None, "failed": False}


def watermark(wav, sr: int = 44100):
    """The inaudible AudioSeal watermark (16 bits, made at 16 kHz and added at full strength). If AudioSeal can't load,
    the audio is returned unchanged and only the file label marks it (a warning is printed)."""
    import torch
    with _WM["lock"]:
        if _WM["gen"] is None and not _WM["failed"]:
            try:
                from audioseal import AudioSeal
                try:
                    import audioseal.libs.moshi.utils.compile as _asc
                    _asc._compile_disabled = True
                except Exception:  # noqa: BLE001
                    pass
                _WM["gen"] = AudioSeal.load_generator("audioseal_wm_16bits").eval()
            except Exception as e:  # noqa: BLE001
                _WM["failed"] = True
                print(f"marking: AudioSeal unavailable ({e}); the audio is labelled in the file only. pip install audioseal", flush=True)
        gen = _WM["gen"]
    if gen is None:
        return np.asarray(wav, dtype=np.float32)
    import torchaudio.functional as AF
    with torch.no_grad():
        x = torch.as_tensor(np.asarray(wav, dtype=np.float32))[None, None]
        x16 = AF.resample(x, sr, 16000)
        wm = AF.resample(gen.get_watermark(x16, 16000), 16000, sr)[..., : x.shape[-1]]
        if wm.shape[-1] < x.shape[-1]:
            wm = torch.nn.functional.pad(wm, (0, x.shape[-1] - wm.shape[-1]))
        return (x + wm).clamp(-1.0, 1.0)[0, 0].numpy()


def ai_wav(wav, sr: int = 44100) -> bytes:
    """WAV bytes: 16-bit mono, labelled as AI-generated inside the file and watermarked in the sound."""
    import soundfile as sf
    buf = io.BytesIO()
    with sf.SoundFile(buf, "w", samplerate=sr, channels=1, format="WAV", subtype="PCM_16") as f:
        f.title = "AI-generated speech"
        f.artist = "Grey (AI voice, not a real recording)"
        f.software = "Grey text-to-speech, thisvoiceisai.com"
        f.comment = COMMENT
        f.date = time.strftime("%Y-%m-%d")
        f.write(watermark(wav, sr))
    return buf.getvalue()


def write_ai_wav(path, wav, sr: int = 44100) -> Path:
    p = Path(path)
    p.write_bytes(ai_wav(wav, sr))
    return p


def detect(path_or_wav, sr: int = None) -> float:
    """The watermark detector's score, 0..1 (above 0.5: the mark is there)."""
    import soundfile as sf
    import torch
    import torchaudio.functional as AF
    if isinstance(path_or_wav, (str, Path)):
        w, sr = sf.read(str(path_or_wav), dtype="float32", always_2d=True)
        w = w.mean(1)
    else:
        w = np.asarray(path_or_wav, dtype=np.float32)
    with _WM["lock"]:
        if _WM["det"] is None:
            from audioseal import AudioSeal
            _WM["det"] = AudioSeal.load_detector("audioseal_detector_16bits").eval()
    with torch.no_grad():
        x16 = AF.resample(torch.as_tensor(w)[None, None], sr, 16000)
        score, _ = _WM["det"].detect_watermark(x16, 16000)
    return float(score)
